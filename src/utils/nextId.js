/**
 * ============================================================
 *  nextId — המזהה הבא ברצף
 * ============================================================
 *
 * המזהה הבא = המספר הגדול ביותר הקיים + 1, או base + 1 בקובץ ריק.
 * (courses: base=100 → הראשון 101; students/enrollments: base=0 → הראשון 1)
 *
 * למה לא סתם max + 1? כי אם המזהה הזה כבר תפוס (נתונים לא מסודרים,
 * או מזהה שהועתק ידנית לקובץ), ניכנס ללולאה עד שנמצא מזהה פנוי —
 * ככה אף פעם לא נוצרת רשומה כפולה באותו id.
 *
 * את הקריאה יש לבצע *בתוך* store.update, על הרשימה הטרייה שנקראה
 * תחת ה-mutex — כך שתי בקשות מקבילות לא מקבלות אותו id.
 *
 * שים לב: מחיקת הרשומה בעלת המזהה הגבוה ביותר משחררת את המזהה הזה
 * לשימוש חוזר. זה מקובל כיום; אם נרצה מזהים שלא חוזרים לעולם,
 * צריך לשמור "קו מים גבוה" (high-water mark) בקובץ או בתהליך.
 */
export const nextId = (items, base) => {
  const max = items.length > 0 ? Math.max(...items.map((item) => item.id)) : base;
  const taken = new Set(items.map((item) => item.id));

  let candidate = max + 1;
  while (taken.has(candidate)) {
    candidate++;
  }
  return candidate;
};
